"""Summarize raw measurements using Python's standard library only."""
import csv
import math
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

root = Path(__file__).resolve().parent
groups = defaultdict(list)
for path in ([Path(p) for p in sys.argv[1:]] or sorted(root.glob('threshold-[0-9]*.csv'))):
    for row in csv.DictReader(path.open()):
        assert row['ns'] is not None, f'Incomplete CSV: {path}; wait for benchmark completion'
        key = tuple(row[k] for k in ['threads','target_bytes','excerpt','actual_bytes','chunks','operation','threshold'])
        groups[key].append(int(row['ns']))

def percentile(values, p):
    values = sorted(values)
    x = (len(values)-1)*p
    a = int(x)
    return values[a]+(values[min(a+1,len(values)-1)]-values[a])*(x-a)

med = {}
actual_bytes = {}
with (root/'threshold-summary.csv').open('w', newline='') as f:
    writer = csv.writer(f)
    writer.writerow(['threads','target_bytes','excerpt','actual_bytes','chunks','operation','threshold','n','median_us','p10_us','p90_us','mad_us','MiB_s'])
    for key, values in sorted(groups.items()):
        assert len(values) == 12, (key, len(values))
        m = st.median(values)
        case = (int(key[0]),int(key[1]),int(key[2]),key[5],int(key[6]))
        med[case] = m
        actual_bytes[case] = int(key[3])
        writer.writerow([*key,len(values),m/1000,percentile(values,.1)/1000,percentile(values,.9)/1000,st.median(abs(x-m) for x in values)/1000,int(key[3])*1e9/m/1048576])

seq = 2**64-1
threads = sorted({k[0] for k in med})
sizes = sorted({k[1] for k in med})
ops = list(dict.fromkeys(k[3] for k in med))
lines = ['# Measurement tables','', 'Generated by `python benchmarks/analyze_threshold.py`. Times include output destruction. MiB/s uses input UTF-8 bytes. P10–P90 describes observed iteration spread, not a confidence interval.','']
for t in threads:
    lines += [f'## {t} Rayon workers','', '### Candidate comparison','', 'Scores are geometric means of per-case candidate/sequential median ratios over the 14 excerpt sizes and three positions. Each size, excerpt, and operation has equal weight; full novel excluded. Lower is better. This is a synthetic workload score, not a production traffic estimate.','', '| Threshold (bytes) | All operations ratio | Join HMM off ratio | Join HMM on ratio | Summed median time (ms) |','|---:|---:|---:|---:|---:|']
    keys = [k for k in med if k[0]==t and k[1]!=max(sizes) and k[4]==seq]
    for c in range(1000,10000,1000):
        scores = []
        for op in [None,'join_off','join_on']:
            ratios = [med[k[:4]+(c,)]/med[k] for k in keys if op is None or k[3]==op]
            scores.append(math.exp(st.mean(math.log(r) for r in ratios)))
        total = sum(med[k[:4]+(c,)] for k in keys)/1e6
        lines.append(f'| {c} | {scores[0]:.3f} | {scores[1]:.3f} | {scores[2]:.3f} | {total:.3f} |')
    lines += ['', '### Forced sequential versus parallel','', 'Excerpt rows show the median of the three excerpt medians. Wins count excerpts with a lower parallel median; ratio is parallel/sequential. Full novel uses one sample.','']
    for op in ops:
        lines += [f'#### {op}','', '| Target bytes | Sequential µs | Parallel µs | Parallel/seq | Parallel wins | Seq MiB/s | Par MiB/s |','|---:|---:|---:|---:|---:|---:|---:|']
        for size in sizes:
            ks = [k for k in med if k[:2]==(t,size) and k[3:]==(op,seq)]
            if not ks: continue
            a = st.median(med[k] for k in ks)
            b = st.median(med[k[:4]+(0,)] for k in ks)
            wins = sum(med[k[:4]+(0,)]<med[k] for k in ks)
            seq_rates = [actual_bytes[k]*1e9/med[k]/1048576 for k in ks]
            par_rates = [actual_bytes[k]*1e9/med[k[:4]+(0,)]/1048576 for k in ks]
            lines.append(f'| {size} | {a/1000:.2f} | {b/1000:.2f} | {b/a:.3f} | {wins}/{len(ks)} | {st.median(seq_rates):.2f} | {st.median(par_rates):.2f} |')
        lines.append('')
    lines += ['', '### Full-novel candidate variation','', '| Operation | Threshold | Median ms | P10–P90 ms | MiB/s |','|---|---:|---:|---:|---:|']
    for key, values in sorted(groups.items()):
        if int(key[0])!=t or int(key[1])!=max(sizes): continue
        m = st.median(values)
        lines.append(f'| {key[5]} | {key[6]} | {m/1e6:.3f} | {percentile(values,.1)/1e6:.3f}–{percentile(values,.9)/1e6:.3f} | {int(key[3])*1e9/m/1048576:.2f} |')
(root/'threshold-tables.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'{len(groups)} cases, {sum(map(len,groups.values()))} measurements')
